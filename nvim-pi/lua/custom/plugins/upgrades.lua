-- READ PYWAL COLORS DYNAMICALLY
local wal_colors_path = vim.fn.expand '~/.cache/wal/colors.json'
local pywal = {}

if vim.fn.filereadable(wal_colors_path) == 1 then
  local file = io.open(wal_colors_path, 'r')
  if file then
    local content = file:read '*a'
    file:close()
    -- Parse the JSON file generated by Pywal
    local status_ok, parsed = pcall(vim.fn.json_decode, content)
    if status_ok and parsed and parsed.colors then pywal = parsed.colors end
  end
end

-- SETUP CYBERDREAM (Injecting Pywal Palette)
require('cyberdream').setup {
  transparent = true, -- Keeps the Hyprland glass effect active
  italic_comments = true,
  theme = {
    variant = 'dark',
  },

  -- Inject the dynamic Pywal tokens directly into Neovim
  colors = {
    dark = pywal.color1 and {
      bg = pywal.color0, -- Keep Pywal's dynamic background
      fg = '#ffffff', -- OVERRIDE: Pure white text for max readability
      red = pywal.color1,
      green = pywal.color2,
      yellow = pywal.color3,
      blue = pywal.color4,
      magenta = pywal.color5,
      cyan = pywal.color6,
      pink = pywal.color13,
      orange = pywal.color11,
    } or {},
  },

  highlights = {
    -- OVERRIDE: Light purple for comments. For dark pink, use '#ff7eb6' instead.
    Comment = { fg = '#cba6f7', italic = true },
  },
} -- THEME ACTIVATION
